describe('probabilityScale is the exact chi-square(3) quantile', () => {
    it('matches scipy.stats.chi2.ppf to 1e-10 on p = 0.01 .. 0.999', () => {
        let worst = 0;
        SCIPY_K.forEach(([p, expected]) => {
            const rel = Math.abs(probabilityScale(p) - expected) / expected;
            worst = Math.max(worst, rel);
        });
        expect(worst).toBeLessThan(1e-10);
    });

    it('is exact at the 1-sigma (0.6827) and 3-sigma (0.9973) presets', () => {
        const at = (p) => SCIPY_K.find(([q]) => q === p)[1];
        expect(Math.abs(probabilityScale(0.6827) - at(0.6827))).toBeLessThan(1e-10);
        expect(Math.abs(probabilityScale(0.9973) - at(0.9973))).toBeLessThan(1e-10);
    });

    it('stays finite and monotonic at extreme probabilities', () => {
        const ps = [1e-12, 1e-6, 1e-3, 0.5, 1 - 1e-6, 1 - 1e-12];
        const ks = ps.map(probabilityScale);
        ks.forEach((k) => expect(Number.isFinite(k)).toBe(true));
        for (let i = 1; i < ks.length; i += 1) expect(ks[i]).toBeGreaterThan(ks[i - 1]);
    });

    it('rejects probabilities outside (0, 1) and non-finite input', () => {
        for (const bad of [0, 1, -0.1, 1.2, Number.NaN, Infinity, 'abc']) {
            expect(() => probabilityScale(bad)).toThrow();
        }
    });
});
