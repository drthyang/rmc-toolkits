const BY_SYMBOL = new Map();
for (const [number, symbol, pointGroup, legacy] of SPACE_GROUPS) {
  BY_SYMBOL.set(symbol, { number, symbol, pointGroup });
  if (legacy) BY_SYMBOL.set(legacy, { number, symbol, pointGroup });
}

/** Space-group number for a Hermann-Mauguin symbol, or null if it is not a standard one. */
export function spaceGroupNumber(symbol) {
  return BY_SYMBOL.get(symbol)?.number ?? null;
}

/** True when `symbol` is a space group in its standard ITA setting (or a legacy spelling). */
export function isStandardSymbol(symbol) {
  return BY_SYMBOL.has(symbol);
}

/** The standard (current-ITA) spelling of a symbol, or null. Maps Cmca -> Cmce. */
export function canonicalSymbol(symbol) {
  return BY_SYMBOL.get(symbol)?.symbol ?? null;
}

/** The crystal class of a space-group symbol, or null. */
export function pointGroupOfSymbol(symbol) {
  return BY_SYMBOL.get(symbol)?.pointGroup ?? null;
}

export { SPACE_GROUPS };
